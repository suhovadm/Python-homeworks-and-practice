# Главный файл программы. Связывает все модули между собой.

from console_utils import read_input_command # Импортируем функцию ввода команд.
from subnet_calculator import calculate_subnet # Импортируем функцию расчёта подсети.

# Главная функция программы. Основной бесконечный цикл.
def main() -> None:
    print("Калькулятор шлюзов по умолчанию для IPv4-подсетей.")
    print("Основные команды: history, cls, clear.")
    print("Для выхода из программы наберите exit, quit или нажмите Ctrl + C.")
    print()

    # Главный бесконечный цикл.
    # Работает до тех пор, пока пользователь сам не завершит программу.
    while(True):
        # Запрашиваем IP-адрес.
        ip = read_input_command("Введите IP-адрес")

        # Запрашиваем маску подсети.
        mask = read_input_command(
            "Введите маску подсети (например, 28 "
            "или 255.255.255.240)"
        )

        # Передаём введённые данные в модуль расчёта.
        calculate_subnet(ip, mask)

# Точка входа в программу.
if __name__ == "__main__":
    try:
        main()

    # Дополнительная обработка Ctrl + C на случай,
    # если прерывание произойдёт вне функции ввода.
    except KeyboardInterrupt:
        print("\nЗавершение программы.")