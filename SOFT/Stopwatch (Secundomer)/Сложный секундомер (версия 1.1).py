import time # Модуль для работы со временем.
import threading # Модуль для работы с потоками.
import sys # Модуль для работы с системным вводом-выводом.

print()
print('Сложный секундомер. Версия 1.1')

# Основной функционал программы.
def run_stopwatch():

    # Создаём событие stop_event.
    # threading.Event() - объект синхронизации, который служит для передачи сигнала между потоками.
    # В данном случае, он будет сигналом о том, что пользователь нажал Enter, и секундомер нужно остановить.
    stop_event = threading.Event()

    # Вложенная функция wait().
    # Эта функция просто ожидает нажатия клавиши Enter (блокирующий вызов input()).

    def wait():
        try:
            input()

            # После нажатия она вызывает stop_event.set(), говоря нам о том, что
            # секундомер нужно остановить.
            stop_event.set()

        except Exception as e:

            # Если произошла ошибка при чтении ввода (например, при нажатии Stop в PyCharm)
            # все равно устанавливаем событие остановки.
            stop_event.set()

    # Запуск потока для ожидания кнопки.
    # Создаём новый поток (Thread), который выполняет функцию wait.
    # deamon=True - поток, который будет работать "в фоне" и завершится автоматически при завершении
    # основной программы.
    # start() - запускает поток.
    threading.Thread(target=wait, daemon=True).start()

    # Запоминаем начальное время.
    start = time.time()

    print('Секундомер запущен. Нажмите Enter, чтобы остановить.\n')

    # Данный try / except сделан скорее для безопасности, чтобы избежать ошибок выхода из цикла.
    try:

        # Основной цикл отслеживания времени.
        # while not stop_event.is_set() - цикл работает, пока пользователь не нажмёт Enter
        # то есть, пока событие stop_event не установлено.
        while not stop_event.is_set():

            # Внутри цикла.
            # sys.stdout.write() - выводит текущий прошедший таймер, используя возврат каретки \r
            # для перезаписи строки в консоли.
            # f'\rПрошло: {time.time() - start:.2f} сек. - f-строка, показывающая прошедшее время
            # с точностью до двух знаков после запятой.
            sys.stdout.write(f'\rПрошло: {time.time() - start:.2f} сек.')

            # Принудительно выводит содержимое буфера на экран, чтобы обновление было
            # мгновенным.
            sys.stdout.flush()

            # Задержка 0.1 секунды для снижения нагрузки и обновления времени примерно каждую десятую секунды.
            time.sleep(0.1)
    except:
        pass

    # Расчёт и вывод итогового времени.
    # После выхода из цикла (когда пользователь нажмёт Enter), программа вычисляет прошедшее время.
    # Выводится сообщение с итоговым временем.
    # Возвращается значение прошедшего времени (может быть использовано, если функция вызывается повторно).
    elapsed = time.time() - start
    print(f'\nСекундомер остановлен. Итог: {elapsed:.2f} сек.')
    return elapsed

# Основной цикл программы.
while(True):

    # Вызывает run_stopwatch() - запускает секундомер.
    run_stopwatch()

    print("Нажмите Enter для перезапуска.")

    # try / except - ловит ошибки ввода (например, при нажатии Stop в PyCharm),
    # чтобы корректно продолжить работу программы при нестандартном вводе.
    try:
        input()
    except Exception:
        # Игнорируем ошибки ввода при перезапуске.
        pass
