funcs = []

for i in range(3):
    def f():
        return i
    funcs.append(f)

print([f() for f in funcs])

# Что будет выведено в результате работы цикла и почему?
# Код выведет: [2, 2, 2]

# Почему так?
# В Python замыкания (closures) захватывают переменную, а не её значение.

# В цикле: for i in range(3):
# переменная i принимает значение 0, 1, 2.
# Но функция f() внутри цикла не запоминает текущее значение i в момент создания.
# Она запоминает саму переменную i.

# Когда цикл завершится, i будет равно 2.
# И все три функции в списке funcs при вызове обращаются к одной и той же переменной i,
# которая к этому моменту равна 2.

# Поэтому:
# [f() for f in funcs]
# вызывает три функции, каждая из которых возвращает текущее значение i, то есть 2.

# Можно ли сделать, чтобы вывод был [0, 1, 2]?
# Да, нужно зафиксировать значение i в момент создания функции, например, через аргумент по умолчанию:

# funcs = []
# for i in range(3):
#   def f(i=i):
#       return i
#   funcs.append(f)

# print([f() for f in funcs])
# Теперь аргумент i=i сохраняет текущее значение переменной, и вывод будет:
# [0, 1, 2]